# Функция сортировки слиянием возвращает отсортированный список.
def merge_sort(A):

    # База рекурсии: список из нуля или одного элемента уже отсортирован.
    if len(A) <= 1:
        # Возвращаем список вызывающему коду.
        return A

    # Находим середину; // делит целые числа с округлением вниз.
    mid = len(A) // 2
    # Срез копирует элементы до mid, не включая mid.
    left = A[:mid]
    # Срез копирует элементы от mid до конца.
    right = A[mid:]

    # Функция вызывает сама себя, чтобы отсортировать левую половину.
    left = merge_sort(left)
    # Таким же образом сортируем правую половину.
    right = merge_sort(right)

    # Объединяем две отсортированные половины и возвращаем результат.
    return merge(left, right)

# Функция слияния двух уже отсортированных списков.
def merge(left, right):

    # Создаём пустой список для результата.
    result = []
    # Начинаем чтение левой половины с позиции 0.
    i = 0  # индекс для left
    # Начинаем чтение правой половины с позиции 0.
    j = 0  # индекс для right

    # Продолжаем, пока в обеих половинах есть непрочитанные элементы.
    while i < len(left) and j < len(right):

        # Из двух текущих элементов выбираем меньший; при равенстве берём левый.
        if left[i] <= right[j]:
            # Добавляем текущий левый элемент в конец результата.
            result.append(left[i])
            # Переходим к следующему элементу слева.
            i += 1
        # Выполняем эту ветку, когда предыдущее условие не выполнено.
        else:
            # Добавляем текущий правый элемент в результат.
            result.append(right[j])
            # Переходим к следующему элементу справа.
            j += 1

    # Если слева остались элементы, дописываем их по порядку.
    while i < len(left):
        # Добавляем текущий левый элемент в конец результата.
        result.append(left[i])
        # Переходим к следующему элементу слева.
        i += 1

    # Если справа остались элементы, дописываем их по порядку.
    while j < len(right):
        # Добавляем текущий правый элемент в результат.
        result.append(right[j])
        # Переходим к следующему элементу справа.
        j += 1

    # Возвращаем новый отсортированный список.
    return result

# Читаем количество элементов и преобразуем строку в целое число.
n = int(input())
# Читаем строку; split делит её, int превращает каждую часть в число, list собирает список.
A = list(map(int, input().split()))

# Сохраняем возвращённый отсортированный список в переменной A.
A = merge_sort(A)

# Звёздочка распаковывает список: print выводит числа через пробел.
print(*A)


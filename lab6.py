# Функция быстрой сортировки возвращает новый упорядоченный список.
def quick_sort(A):

    # База рекурсии: список из нуля или одного элемента уже отсортирован.
    if len(A) <= 1:
        # Возвращаем список вызывающему коду.
        return A

    # Берём значение из средней позиции как опорное; это не обязательно медиана.
    pivot = A[len(A) // 2]

    # Список для чисел меньше опорного.
    left = []

    # Список для чисел, равных опорному.
    middle = []

    # Список для чисел больше опорного.
    right = []

    # Последовательно берём каждое значение из A.
    for x in A:
        # Проверяем, меньше ли число опорного.
        if x < pivot:
            # Добавляем число в левую группу.
            left.append(x)
        # Иначе проверяем равенство опорному; == сравнивает значения.
        elif x == pivot:
            # Добавляем равное число в среднюю группу.
            middle.append(x)
        # Выполняем эту ветку, когда предыдущее условие не выполнено.
        else:
            # Оставшееся число больше опорного: добавляем справа.
            right.append(x)

    # Сортируем крайние группы рекурсивно; + соединяет списки, средняя группа уже упорядочена.
    return quick_sort(left) + middle + quick_sort(right)

# Читаем количество элементов и преобразуем строку в целое число.
n = int(input())
# Читаем строку; split делит её, int превращает каждую часть в число, list собирает список.
A = list(map(int, input().split()))

# Заменяем A результатом вызова быстрой сортировки.
A = quick_sort(A)

# Звёздочка распаковывает список: print выводит числа через пробел.
print(*A)


# C. Сортировка пузырьком по невозрастанию: большие числа идут первыми.
def BubbleSort(A):
    # len(A) — число элементов; i — номер прохода, начиная с нуля.
    for i in range(len(A)):
        # Последние i элементов уже стоят на своих местах.
        for j in range(len(A) - 1 - i):
            # Если слева число меньше, соседей нужно переставить.
            if A[j] < A[j + 1]:
                # Одновременно меняем два значения местами без второго списка.
                A[j], A[j + 1] = A[j + 1], A[j]
    # Возвращаем тот же список, уже отсортированный.
    return A


# input читает строку, split делит её, map(int, ...) превращает части в числа.
A = list(map(int, input().split()))
# Вызываем функцию: она изменяет сам список A.
BubbleSort(A)
# Звёздочка распаковывает список: числа выводятся через пробел.
print(*A)

# H. Сортировка точек по расстоянию от начала координат.
# Класс Point объединяет две координаты в один объект — аналог структуры.
class Point:
    # __init__ автоматически вызывается при создании Point(x, y).
    def __init__(self, x, y):
        # self — создаваемая точка; сохраняем её горизонтальную координату.
        self.x = x
        # Сохраняем вертикальную координату этой же точки.
        self.y = y

    # Метод возвращает квадрат расстояния: корень для сравнения не нужен.
    def distance_squared(self):
        # ** 2 означает возведение в квадрат; отрицательные координаты допустимы.
        return self.x ** 2 + self.y ** 2


# Сортируем точки вставками: слева постепенно растёт отсортированная часть.
def InsertionSort(A):
    # Первый элемент сам по себе уже отсортирован, поэтому начинаем с индекса 1.
    for i in range(1, len(A)):
        # Запоминаем точку, для которой будем искать место.
        current = A[i]
        # Начинаем сравнение с предыдущей точки.
        j = i - 1
        # Сдвигаем более далёкие точки вправо; j >= 0 защищает границу списка.
        while j >= 0 and A[j].distance_squared() > current.distance_squared():
            # Освобождаем место, копируя ссылку на точку на позицию справа.
            A[j + 1] = A[j]
            # Переходим к следующей точке слева.
            j -= 1
        # Вставляем сохранённую точку; равные расстояния сохраняют исходный порядок.
        A[j + 1] = current
    # Возвращаем отсортированный список объектов Point.
    return A


# Первая строка содержит количество точек.
n = int(input())
# Создаём пустой список для точек.
A = []
# Повторяем чтение n раз; номер повтора не нужен, поэтому используем _.
for _ in range(n):
    # Читаем два целых числа и записываем их в x и y.
    x, y = map(int, input().split())
    # Создаём объект Point и добавляем его в список.
    A.append(Point(x, y))
# Упорядочиваем список по квадратам расстояний.
InsertionSort(A)
# Перебираем точки в полученном порядке.
for point in A:
    # Выводим только координаты; количество точек повторять не нужно.
    print(point.x, point.y)

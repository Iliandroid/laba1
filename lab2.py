# Объявляем функцию сортировки вставками.
def InsertionSort(A):

    # Начинаем со второго элемента: один первый элемент уже отсортирован.
    for i in range(1, len(A)):

        # Сохраняем вставляемое число перед сдвигом остальных.
        current = A[i]

        # Смотрим на соседнюю позицию слева.
        j = i - 1

        # Пока не вышли за левую границу и встретили большее число, продолжаем сдвиг.
        while j >= 0 and A[j] > current:
            # Копируем большее число на одну позицию вправо.
            A[j + 1] = A[j]
            # Сдвигаем индекс влево; сокращение для j = j - 1.
            j -= 1

        # Вставляем сохранённое число сразу после последнего проверенного меньшего или равного.
        A[j + 1] = current

    # Возвращаем список вызывающему коду.
    return A

# Читаем строку; split делит её, int превращает каждую часть в число, list собирает список.
A = list(map(int, input().split()))

# Сортируем A по неубыванию на месте.
InsertionSort(A)

# Звёздочка распаковывает список: print выводит числа через пробел.
print(*A)


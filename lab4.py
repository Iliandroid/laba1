# Читаем количество элементов и преобразуем строку в целое число.
n = int(input())
# Читаем строку; split делит её, int превращает каждую часть в число, list собирает список.
A = list(map(int, input().split()))

# Счётчик выполненных обменов пока равен нулю.
swaps = 0

# Выполняем последовательные проходы пузырьковой сортировки.
for i in range(n):
    # Сравниваем соседей; последние i элементов уже стоят правильно.
    for j in range(n - 1 - i):

        # Если слева число больше, порядок по неубыванию нарушен.
        if A[j] > A[j + 1]:

            # Меняем соседние числа местами одним присваиванием.
            A[j], A[j + 1] = A[j + 1], A[j]

            # Увеличиваем количество обменов на один.
            swaps += 1

# В этой задаче выводим число обменов, а не отсортированный список.
print(swaps)


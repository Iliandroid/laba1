# Сортировка подсчётом изменяет исходный список A.
def CountSort(A):

    # Создаём 101 нулевой счётчик для допустимых чисел от 0 до 100 включительно.
    count = [0] * 101

    # Последовательно берём каждое значение из A.
    for x in A:
        # Число x служит индексом своего счётчика; увеличиваем число его появлений.
        count[x] += 1

    # Индекс следующей позиции, которую заполним в A.
    idx = 0
    # Перебираем допустимые значения по возрастанию: 0, 1, ..., 100.
    for num in range(101):
        # Повторяем запись num столько раз, сколько оно встречалось.
        while count[num] > 0:
            # Записываем очередное значение в исходный список.
            A[idx] = num
            # Переходим к следующей позиции результата.
            idx += 1
            # Одно вхождение записали, уменьшаем остаток.
            count[num] -= 1

# Читаем строку; split делит её, int превращает каждую часть в число, list собирает список.
A = list(map(int, input().split()))

# Вызываем функцию; она меняет A, поэтому присваивание результата не нужно.
CountSort(A)

# Звёздочка распаковывает список: print выводит числа через пробел.
print(*A)


# Функция сортирует список A выбором максимума.
def SelectionSort(A):
    # Перебираем позиции от 0 до длины списка минус один.
    for i in range(len(A)):

        # Сначала считаем максимальным первый элемент ещё не обработанной части.
        biggest = i

        # Проверяем все позиции справа от i.
        for j in range(i + 1, len(A)):

            # Сравниваем число с текущим найденным максимумом.
            if A[j] > A[biggest]:
                # Запоминаем индекс большего числа.
                biggest = j

        # Одновременно меняем местами два значения; максимум оказывается слева.
        A[i], A[biggest] = A[biggest], A[i]

    # Возвращаем список вызывающему коду.
    return A

# Читаем строку; split делит её, int превращает каждую часть в число, list собирает список.
A = list(map(int, input().split()))
# Запускаем сортировку; функция изменяет сам список A.
SelectionSort(A)
# Звёздочка распаковывает список: print выводит числа через пробел.
print(*A)

